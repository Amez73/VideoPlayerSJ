@Composable
fun EmptyLibraryState(onAddFolder: () -> Unit, modifier: Modifier = Modifier) {
    Column(
        modifier = modifier.fillMaxSize().padding(32.dp),
        horizontalAlignment = Alignment.CenterHorizontally,
        verticalArrangement = Arrangement.spacedBy(16.dp, Alignment.CenterVertically),
    ) {
        Text("No videos yet", textAlign = TextAlign.Center)
        Text("Add a folder to scan for downloaded shows and movies.", textAlign = TextAlign.Center)
        AddFolderButton(onClick = onAddFolder)
    }
}
